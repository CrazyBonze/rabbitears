def _fill_bars(buf: bytearray) -> None:
    """Paint the SMPTE-style color bars across the top third."""
    bar_w = WIDTH // len(BARS)
    for bi, (r, g, b) in enumerate(BARS):
        x0, x1 = bi * bar_w, (bi + 1) * bar_w
        for y in range(BAR_HEIGHT):
            row = y * WIDTH * 3
            for x in range(x0, x1):
                i = row + x * 3
                buf[i] = r
                buf[i + 1] = g
                buf[i + 2] = b


def _draw_text(buf: bytearray, text: str, scale: int, color: tuple[int, int, int]) -> None:
    """Draw text in the bitmap font, centered in the region below the bars."""
    text_w = len(text) * 8 * scale
    text_h = 8 * scale
    x0 = (WIDTH - text_w) // 2
    y0 = BAR_HEIGHT + (HEIGHT - BAR_HEIGHT - text_h) // 2
    for ci, ch in enumerate(text):
        glyph = FONT_8X8.get(ch, FONT_8X8[" "])
        gx = x0 + ci * 8 * scale
        for row in range(8):
            bits = glyph[row]
            for col in range(8):
                if not bits & (0x80 >> col):
                    continue
                for sy in range(scale):
                    y = y0 + row * scale + sy
                    if not 0 <= y < HEIGHT:
                        continue
                    for sx in range(scale):
                        x = gx + col * scale + sx
                        if not 0 <= x < WIDTH:
                            continue
                        i = (y * WIDTH + x) * 3
                        buf[i] = color[0]
                        buf[i + 1] = color[1]
                        buf[i + 2] = color[2]


def _apply_scanlines(buf: bytearray) -> None:
    """Dim every other horizontal line to 85% brightness (CRT texture)."""
    for y in range(1, HEIGHT, 2):
        row = y * WIDTH * 3
        for i in range(row, row + WIDTH * 3, 3):
            buf[i] = int(buf[i] * SCANLINE_FACTOR)
            buf[i + 1] = int(buf[i + 1] * SCANLINE_FACTOR)
            buf[i + 2] = int(buf[i + 2] * SCANLINE_FACTOR)


def _save_png(path: Path, buf: bytearray) -> None:
    """Write the RGB buffer to a PNG using only stdlib (zlib + struct)."""

    def chunk(tag: bytes, data: bytes) -> bytes:
        body = tag + data
        return struct.pack("!I", len(data)) + body + struct.pack("!I", zlib.crc32(body))

    stride = WIDTH * 3
    raw = bytearray()
    for y in range(HEIGHT):
        raw.append(0)  # per-scanline filter type: None
        raw += buf[y * stride:(y + 1) * stride]
    ihdr = struct.pack("!IIBBBBB", WIDTH, HEIGHT, 8, 2, 0, 0, 0)
    png = (
        b"\x89PNG\r\n\x1a\n"
        + chunk(b"IHDR", ihdr)
        + chunk(b"IDAT", zlib.compress(bytes(raw)))
        + chunk(b"IEND", b"")
    )
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(png)


def generate(output_path: Path | str = Path(__file__).with_name("testpattern.png")) -> Path:
    """Render the NO SIGNAL test card and write it to ``output_path``.

    Idempotent: overwrites any existing file. Returns the output path.
    """
    buf = bytearray(WIDTH * HEIGHT * 3)  # black background
    _fill_bars(buf)
    _draw_text(buf, TEXT, TEXT_SCALE, (255, 255, 255))
    _apply_scanlines(buf)
    out = Path(output_path)
    _save_png(out, buf)
    return out


def main() -> int:
    out = generate()
    try:
        shown = out.resolve().relative_to(Path.cwd())
    except ValueError:  # output outside cwd; show the absolute path
        shown = out
    print(f"generated {shown} ({WIDTH}x{HEIGHT})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
