#!/usr/bin/env python3
"""Generate tools/testpattern.png — the Rabbit Ears "NO SIGNAL" screen.

A 1980s/90s-style analog broadcast test card (SCOPE §4.7): SMPTE-style
color bars across the top third, "NO SIGNAL" in large white bitmap text,
and a CRT scan-line texture over the whole frame. 1280x720 (720p max per
SCOPE §5), stdlib only (zlib + struct — no Pillow, no numpy).

Run directly:

    python3 tools/generate_testpattern.py
    # -> writes tools/testpattern.png and prints:
    #    generated tools/testpattern.png (1280x720)

Idempotent: safe to re-run, overwrites silently.
"""

from __future__ import annotations

